#!/usr/bin/env python3
"""Пишет web/js/llm-dev-config.js — только подстановка OLLAMA_API_KEY в dev (не в git)."""

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "js" / "llm-dev-config.js"
KEY = os.environ.get("OLLAMA_API_KEY", "").strip()


def main():
    lines = ["// Generated by scripts/write_llm_dev_config.py — do not commit"]
    if KEY:
        lines.append(f"window.__HARNESS_LLM_API_KEY = {json.dumps(KEY)};")
    else:
        lines.append("// OLLAMA_API_KEY not set")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({'with key' if KEY else 'no key'})", flush=True)


if __name__ == "__main__":
    main()
